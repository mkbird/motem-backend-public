_AI_ZONE_TEMPLATE = """\
# ═══════════════════════════════════════════════════════════════════════════════
#  AI ZONE — catch_v1 archetype (generated by RecipeCompiler).
#  Player controls a catcher at the bottom via body-pose / face X.
#  Drops give score; obstacles cost a life. Win at score __WIN_SCORE__.
#
#  Rendering: Sprite textures from `res://assets/{player,drop,obstacle}.png`
#  (Compiler copies them in from the fast-path catalog). If a texture is null
#  (asset missing), falls back to draw_circle with the catalog color.
# ═══════════════════════════════════════════════════════════════════════════════

func _init_game() -> void:
\tgame.catcher_x = screen_size.x * 0.5
\tgame.catcher_y = screen_size.y - 100.0
\tgame.drops = []
\tgame.obstacles = []
\tgame.spawn_timer = 0.6
\tscore = 0
\tlives = __MAX_LIVES__
\tbgm_track = "__BGM__"
\t# Load sprites once; null-safe (_safe_load_texture returns null on miss)
\tgame.player_tex = _safe_load_texture("res://assets/player.png")
\tgame.drop_tex = _safe_load_texture("res://assets/drop.png")
\tgame.obstacle_tex = _safe_load_texture("res://assets/obstacle.png")


func _update_gameplay(delta: float) -> void:
\tanim_timer += delta

\t# Catcher follows body / face X with lerp
\tvar target: Vector2 = get_body_target(60.0)
\tvar cur_x: float = float(game.catcher_x)
\tgame.catcher_x = lerpf(cur_x, target.x, 12.0 * delta)

\t# Spawn loop
\tvar st: float = float(game.spawn_timer) - delta
\tif st <= 0.0:
\t\tst = __SPAWN_INTERVAL__
\t\t_spawn_falling_item()
\tgame.spawn_timer = st

\t# Move falling items
\tfor d in game.drops:
\t\td["y"] = float(d["y"]) + float(d["v"]) * delta
\tfor o in game.obstacles:
\t\to["y"] = float(o["y"]) + float(o["v"]) * delta

\t# Collision + cleanup
\tvar cx: float = float(game.catcher_x)
\tvar cy: float = float(game.catcher_y)
\tvar rad: float = __CATCHER_RADIUS__
\tvar rad_sq: float = rad * rad

\tvar kept_drops: Array = []
\tfor d in game.drops:
\t\tvar dx_d: float = float(d["x"]) - cx
\t\tvar dy_d: float = float(d["y"]) - cy
\t\tif dx_d * dx_d + dy_d * dy_d < rad_sq:
\t\t\tscore += __SCORE_VALUE__
\t\t\t_audio_play("__SFX_PICKUP__")
\t\telif float(d["y"]) < screen_size.y + 80.0:
\t\t\tkept_drops.append(d)
\tgame.drops = kept_drops

\tvar kept_obs: Array = []
\tfor o in game.obstacles:
\t\tvar dx_o: float = float(o["x"]) - cx
\t\tvar dy_o: float = float(o["y"]) - cy
\t\tif dx_o * dx_o + dy_o * dy_o < rad_sq:
\t\t\tlives -= __LIVES_COST__
\t\t\t_audio_play("__SFX_HIT__")
\t\telif float(o["y"]) < screen_size.y + 80.0:
\t\t\tkept_obs.append(o)
\tgame.obstacles = kept_obs

\t# Win-by-score
\tif score >= __WIN_SCORE__:
\t\t_audio_play("__SFX_PICKUP__")
\t\tstate = GameState.GAME_OVER


func _draw_gameplay() -> void:
\tvar cx: float = float(game.catcher_x)
\tvar cy: float = float(game.catcher_y)
\tvar rad: float = __CATCHER_RADIUS__
\tvar player_size: float = rad * 2.4

\t# Catcher (player) — pulsing scale for liveliness
\tvar pulse: float = 1.0 + 0.06 * sin(anim_timer * 6.0)
\t_draw_sprite_or_circle(game.player_tex, Vector2(cx, cy), player_size * pulse, rad, __PLAYER_COLOR__)

\t# Drops (collectibles)
\tfor d in game.drops:
\t\tvar dx_f: float = float(d["x"])
\t\tvar dy_f: float = float(d["y"])
\t\t_draw_sprite_or_circle(game.drop_tex, Vector2(dx_f, dy_f), 64.0, 22.0, __DROP_COLOR__)

\t# Obstacles (hazards)
\tfor o in game.obstacles:
\t\tvar ox: float = float(o["x"])
\t\tvar oy: float = float(o["y"])
\t\t_draw_sprite_or_circle(game.obstacle_tex, Vector2(ox, oy), 64.0, 22.0, __OBSTACLE_COLOR__)


# ─── Helpers (catch_v1) ──────────────────────────────────────────────────────

func _spawn_falling_item() -> void:
\tvar sx: float = randf_range(60.0, screen_size.x - 60.0)
\tvar v: float = randf_range(__FALL_MIN__, __FALL_MAX__)
\tif randf() < __OBSTACLE_PROB__:
\t\tgame.obstacles.append({"x": sx, "y": -30.0, "v": v})
\telse:
\t\tgame.drops.append({"x": sx, "y": -30.0, "v": v})


# Draw a centered texture at `pos` sized `sprite_size`. If texture is null
# (sprite asset missing), fall back to a colored circle of radius `circle_rad`.
func _draw_sprite_or_circle(tex: Texture2D, pos: Vector2, sprite_size: float, circle_rad: float, fallback: Color) -> void:
\tif tex != null:
\t\tvar half: float = sprite_size * 0.5
\t\tdraw_texture_rect(tex, Rect2(pos.x - half, pos.y - half, sprite_size, sprite_size), false)
\telse:
\t\tdraw_circle(pos, circle_rad, fallback)
"""


