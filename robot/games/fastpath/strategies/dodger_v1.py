"""dodger_v1 — 躲避 archetype 实现。

玩法：玩家在屏幕底部横向移动（人脸 X / 身体倾斜），**躲开**从上方落下的
危险物。Score = 存活秒数（int），命数归零或 score 达到 win_score 结束。

跟 catch_v1 共用左右位移控制器（face_x lerp），主要差异：
- 没有 drop（可接物）—— 只有 obstacle
- Score 是时间累积，不是 pickup 数
- 障碍密度通常更高（spawn_rate 偏大）

GDScript 模板复用 catch_v1 的 _draw_sprite_or_circle helper 模式，但只渲染
player + obstacle 两类 sprite。
"""

