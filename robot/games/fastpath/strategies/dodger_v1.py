_AI_ZONE_TEMPLATE = """\
# ═══════════════════════════════════════════════════════════════════════════════
#  AI ZONE — dodger_v1 archetype (generated by RecipeCompiler).
#  Player dodges falling hazards. Score = seconds survived.
#  Win at score __WIN_SCORE__ (= __WIN_SCORE__ seconds survived) or lose at lives 0.
# ═══════════════════════════════════════════════════════════════════════════════

func _init_game() -> void:
\tgame.player_x = screen_size.x * 0.5
\tgame.player_y = screen_size.y - 100.0
\tgame.hazards = []
\tgame.spawn_timer = 0.5
\tgame.elapsed = 0.0
\tscore = 0
\tlives = __MAX_LIVES__
\tbgm_track = "__BGM__"
\tgame.player_tex = _safe_load_texture("res://assets/player.png")
\tgame.hazard_tex = _safe_load_texture("res://assets/obstacle.png")


func _update_gameplay(delta: float) -> void:
\tanim_timer += delta
\tgame.elapsed = float(game.elapsed) + delta

\t# Player follows body / face X with lerp
\tvar target: Vector2 = get_body_target(60.0)
\tvar cur_x: float = float(game.player_x)
\tgame.player_x = lerpf(cur_x, target.x, 12.0 * delta)

\t# Spawn hazards
\tvar st: float = float(game.spawn_timer) - delta
\tif st <= 0.0:
\t\tst = __SPAWN_INTERVAL__
\t\t_spawn_hazard()
\tgame.spawn_timer = st

\t# Move hazards down
\tfor h in game.hazards:
\t\th["y"] = float(h["y"]) + float(h["v"]) * delta

\t# Collision + cleanup
\tvar px: float = float(game.player_x)
\tvar py: float = float(game.player_y)
\tvar rad: float = __PLAYER_RADIUS__
\tvar rad_sq: float = rad * rad

\tvar kept: Array = []
\tfor h in game.hazards:
\t\tvar dx_h: float = float(h["x"]) - px
\t\tvar dy_h: float = float(h["y"]) - py
\t\tif dx_h * dx_h + dy_h * dy_h < rad_sq:
\t\t\tlives -= __LIVES_COST__
\t\t\t_audio_play("__SFX_HIT__")
\t\telif float(h["y"]) < screen_size.y + 80.0:
\t\t\tkept.append(h)
\tgame.hazards = kept

\t# Score = elapsed seconds (int)
\tscore = int(float(game.elapsed))
\tif score >= __WIN_SCORE__:
\t\t_audio_play("__SFX_GAMEOVER__")
\t\tstate = GameState.GAME_OVER


func _draw_gameplay() -> void:
\tvar px: float = float(game.player_x)
\tvar py: float = float(game.player_y)
\tvar rad: float = __PLAYER_RADIUS__
\tvar player_size: float = rad * 2.4

\t# Player — pulsing scale
\tvar pulse: float = 1.0 + 0.06 * sin(anim_timer * 6.0)
\t_draw_sprite_or_circle(game.player_tex, Vector2(px, py), player_size * pulse, rad, __PLAYER_COLOR__)

\t# Hazards
\tfor h in game.hazards:
\t\tvar hx: float = float(h["x"])
\t\tvar hy: float = float(h["y"])
\t\t_draw_sprite_or_circle(game.hazard_tex, Vector2(hx, hy), 64.0, 22.0, __HAZARD_COLOR__)


# ─── Helpers (dodger_v1) ─────────────────────────────────────────────────────

func _spawn_hazard() -> void:
\tvar sx: float = randf_range(60.0, screen_size.x - 60.0)
\tvar v: float = randf_range(__FALL_MIN__, __FALL_MAX__)
\tgame.hazards.append({"x": sx, "y": -30.0, "v": v})


func _draw_sprite_or_circle(tex: Texture2D, pos: Vector2, sprite_size: float, circle_rad: float, fallback: Color) -> void:
\tif tex != null:
\t\tvar half: float = sprite_size * 0.5
\t\tdraw_texture_rect(tex, Rect2(pos.x - half, pos.y - half, sprite_size, sprite_size), false)
\telse:
\t\tdraw_circle(pos, circle_rad, fallback)
"""


