_AI_ZONE_TEMPLATE = """\
# ═══════════════════════════════════════════════════════════════════════════════
#  AI ZONE — slicer_v1 archetype (generated by RecipeCompiler).
#  Fruit Ninja-style：水果 / 炸弹抛物线飞入，玩家挥手画出 slice 轨迹切割。
#  cursor 优先 bridge.hand_position（iOS Vision 手腕），无效时退到 face_position。
#  Win at score __WIN_SCORE__ or lose at lives 0.
# ═══════════════════════════════════════════════════════════════════════════════

const TRAIL_MAX: int = 14                # how many recent cursor positions to keep
const MIN_SLICE_SPEED: float = 120.0     # px/sec — below this trail doesn't cut (lowered from 220 for far-distance hand tracking)
const SLICE_RADIUS: float = 52.0         # collision radius cursor-segment ↔ item (wider for less precise hand)
const GRAVITY: float = 480.0             # px/sec^2 downward
const ITEM_RADIUS: float = 36.0


func _init_game() -> void:
\tgame.items = []
\tgame.trail = []                       # Array of {pos: Vector2, t: float}
\tgame.spawn_timer = 0.5
\tgame.elapsed = 0.0
\tgame.last_cursor = Vector2(screen_size.x * 0.5, screen_size.y * 0.5)
\tgame.next_item_id = 0
\tscore = 0
\tlives = __MAX_LIVES__
\tbgm_track = "__BGM__"
\tgame.fruit_tex = _safe_load_texture("res://assets/drop.png")
\tgame.bomb_tex = _safe_load_texture("res://assets/obstacle.png")


func _update_gameplay(delta: float) -> void:
\tanim_timer += delta
\tgame.elapsed = float(game.elapsed) + delta

\t# Cursor from bridge.hand_position with face_position fallback
\tvar cursor: Vector2 = _resolve_cursor()

\t# Maintain trail
\tvar trail: Array = game.trail
\ttrail.append({"pos": cursor, "t": float(game.elapsed)})
\twhile trail.size() > TRAIL_MAX:
\t\ttrail.pop_front()
\tgame.trail = trail

\t# Spawn loop
\tvar st: float = float(game.spawn_timer) - delta
\tif st <= 0.0:
\t\tst = __SPAWN_INTERVAL__
\t\t_spawn_item()
\tgame.spawn_timer = st

\t# Update items (parabolic)
\tvar kept: Array = []
\tfor it in game.items:
\t\tit["x"] = float(it["x"]) + float(it["vx"]) * delta
\t\tit["y"] = float(it["y"]) + float(it["vy"]) * delta
\t\tit["vy"] = float(it["vy"]) + GRAVITY * delta
\t\tit["rot"] = float(it["rot"]) + float(it["spin"]) * delta
\t\tif bool(it.get("cut", false)):
\t\t\tcontinue  # drop already-cut items
\t\t# Keep if still on/near screen
\t\tif float(it["y"]) < screen_size.y + 120.0 and float(it["x"]) > -120.0 and float(it["x"]) < screen_size.x + 120.0:
\t\t\tkept.append(it)
\tgame.items = kept

\t# Slice detection — segment from last_cursor to current cursor
\tvar last_pos: Vector2 = Vector2(float(game.last_cursor.x), float(game.last_cursor.y))
\tvar seg: Vector2 = cursor - last_pos
\tvar seg_len: float = seg.length()
\tvar slice_speed: float = seg_len / max(delta, 0.001)
\tif slice_speed > MIN_SLICE_SPEED:
\t\tfor it in game.items:
\t\t\tif bool(it.get("cut", false)):
\t\t\t\tcontinue
\t\t\tvar ip: Vector2 = Vector2(float(it["x"]), float(it["y"]))
\t\t\tif _seg_point_dist(last_pos, cursor, ip) < SLICE_RADIUS:
\t\t\t\tit["cut"] = true
\t\t\t\tif String(it["kind"]) == "fruit":
\t\t\t\t\tscore += __SCORE_VALUE__
\t\t\t\t\t_audio_play("__SFX_PICKUP__")
\t\t\t\telse:
\t\t\t\t\tlives -= __LIVES_COST__
\t\t\t\t\t_audio_play("__SFX_HIT__")
\tgame.last_cursor = cursor

\t# Win condition
\tif score >= __WIN_SCORE__:
\t\t_audio_play("__SFX_GAMEOVER__")
\t\tstate = GameState.GAME_OVER


func _draw_gameplay() -> void:
\t# Items (rotating sprites)
\tfor it in game.items:
\t\tvar pos: Vector2 = Vector2(float(it["x"]), float(it["y"]))
\t\tvar tex: Texture2D = game.fruit_tex if String(it["kind"]) == "fruit" else game.bomb_tex
\t\tvar fallback_color: Color = __FRUIT_COLOR__ if String(it["kind"]) == "fruit" else __BOMB_COLOR__
\t\t_draw_sprite_rotated(tex, pos, 88.0, float(it["rot"]), ITEM_RADIUS, fallback_color)

\t# Slice trail — fading white glow
\tvar trail: Array = game.trail
\tvar n: int = trail.size()
\tif n >= 2:
\t\tfor i in range(1, n):
\t\t\tvar p0: Vector2 = trail[i-1]["pos"] as Vector2
\t\t\tvar p1: Vector2 = trail[i]["pos"] as Vector2
\t\t\tvar a: float = float(i) / float(n) * 0.85
\t\t\tdraw_line(p0, p1, Color(1.0, 1.0, 1.0, a), 4.0 + 3.0 * (float(i) / float(n)))

\t# Cursor dot (helps user see where their hand is)
\tif bridge != null and (bridge.face_detected or bridge.body_detected):
\t\tvar c: Vector2 = Vector2(float(game.last_cursor.x), float(game.last_cursor.y))
\t\tdraw_circle(c, 10.0, Color(1.0, 0.85, 0.10, 0.9))


# ─── Helpers (slicer_v1) ─────────────────────────────────────────────────────

func _resolve_cursor() -> Vector2:
\t# Prefer hand_position (Phase 3 W3 iOS Vision wrist), fall back to face.
\t# Hand position has full 0-1 range (user can physically swing hand across
\t# full screen width); face position only naturally spans ~0.35-0.65 so we
\t# scale 2× around 0.5 (跟 skeleton get_body_target / 火球掌控 一致).
\tif bridge != null:
\t\tvar hp: Vector2 = bridge.hand_position
\t\tif hp.length() > 0.001:
\t\t\treturn Vector2(hp.x * screen_size.x, hp.y * screen_size.y)
\t\tif bridge.face_detected:
\t\t\tvar fx: float = (bridge.face_position.x - 0.5) * 2.0 + 0.5
\t\t\tvar fy: float = (bridge.face_position.y - 0.5) * 2.0 + 0.5
\t\t\treturn Vector2(fx * screen_size.x, fy * screen_size.y)
\t# No tracking — return last known cursor (so trail doesn't snap to 0,0)
\treturn Vector2(float(game.last_cursor.x), float(game.last_cursor.y))


func _spawn_item() -> void:
\tvar from_left: bool = randf() < 0.5
\tvar start_x: float = -60.0 if from_left else screen_size.x + 60.0
\tvar start_y: float = screen_size.y - randf_range(40.0, 180.0)
\tvar vx_mag: float = randf_range(__VX_MIN__, __VX_MAX__)
\tvar vx: float = vx_mag if from_left else -vx_mag
\tvar vy: float = -randf_range(__VY_MIN__, __VY_MAX__)   # upward launch
\tvar is_bomb: bool = randf() < __BOMB_PROBABILITY__
\tvar kind: String = "bomb" if is_bomb else "fruit"
\tvar new_id: int = int(game.next_item_id)
\tgame.next_item_id = new_id + 1
\tgame.items.append({
\t\t"x": start_x, "y": start_y,
\t\t"vx": vx, "vy": vy,
\t\t"rot": randf_range(0.0, TAU),
\t\t"spin": randf_range(-3.0, 3.0),
\t\t"kind": kind, "cut": false, "id": new_id,
\t})


# Shortest distance from point P to segment AB
func _seg_point_dist(a: Vector2, b: Vector2, p: Vector2) -> float:
\tvar ab: Vector2 = b - a
\tvar ab_sq: float = ab.dot(ab)
\tif ab_sq < 0.0001:
\t\treturn (p - a).length()
\tvar t: float = clampf((p - a).dot(ab) / ab_sq, 0.0, 1.0)
\tvar closest: Vector2 = a + ab * t
\treturn (p - closest).length()


func _draw_sprite_rotated(tex: Texture2D, pos: Vector2, sprite_size: float, rot: float, circle_rad: float, fallback: Color) -> void:
\tif tex != null:
\t\tvar half: float = sprite_size * 0.5
\t\t# Rotate by drawing into transform — use draw_set_transform (works in _draw)
\t\tdraw_set_transform(pos, rot, Vector2.ONE)
\t\tdraw_texture_rect(tex, Rect2(-half, -half, sprite_size, sprite_size), false)
\t\tdraw_set_transform(Vector2.ZERO, 0.0, Vector2.ONE)
\telse:
\t\tdraw_circle(pos, circle_rad, fallback)


"""


