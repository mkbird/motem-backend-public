"""slicer_v1 — 挥砍 archetype 实现（Fruit Ninja 风）。

玩法：水果（drop）/ 炸弹（obstacle）从屏幕左右边缘以抛物线轨迹飞入。玩家
用手位置画出"刀光"轨迹，slice 路径穿过水果 = +score，穿过炸弹 = -life。
得分达 win_score 胜利；命数归零失败。

控制：优先用 `bridge.hand_position`（Phase 3 W3 iOS 端推过来的 Vision 手腕
位置）；hand_position 无效（iOS 未推 / 手部未识别）时**退化到 face_position**
让 face 充当 cursor。这样 backend 即使 iOS 手部追踪没接通也能玩，体验稍差。

误切防御：trail 最近一帧位移速度 < min_slice_speed（默认 200 px/s）时不
触发切割——避免静止 cursor 误碰水果。
"""

