_AI_ZONE_TEMPLATE = """\
# ═══════════════════════════════════════════════════════════════════════════════
#  AI ZONE — whack_v1 archetype (generated by RecipeCompiler).
#  Targets appear randomly; tap (touch) OR face-cursor dwell to hit.
#  Touch path: instant hit on tap. Visual path: cursor follows face_position,
#  stays on target for DWELL_THRESHOLD seconds (0.35s) → auto-hit.
#  Win at score __WIN_SCORE__ or lose at lives 0.
# ═══════════════════════════════════════════════════════════════════════════════

const TAP_RADIUS: float = 60.0
const TARGET_LIFETIME: float = 1.5         # seconds before auto-disappear
const TARGET_FADE_TAIL: float = 0.4
const DWELL_THRESHOLD: float = 0.35        # face stays on target N seconds → hit


func _init_game() -> void:
\tgame.targets = []
\tgame.spawn_timer = 0.5
\tgame.cursor_pos = Vector2(screen_size.x * 0.5, screen_size.y * 0.5)
\tgame.dwell_time = 0.0
\tgame.dwell_anchor_id = -1
\tgame.next_target_id = 0
\tscore = 0
\tlives = __MAX_LIVES__
\tbgm_track = "__BGM__"
\tgame.target_tex = _safe_load_texture("res://assets/drop.png")
\tgame.decoy_tex = _safe_load_texture("res://assets/obstacle.png")


func _update_gameplay(delta: float) -> void:
\tanim_timer += delta

\t# Cursor follows face / body — lerp for smoothness
\tvar tgt: Vector2 = get_body_target(0.0)
\tvar cur_x: float = float(game.cursor_pos.x)
\tvar cur_y: float = float(game.cursor_pos.y)
\tgame.cursor_pos = Vector2(lerpf(cur_x, tgt.x, 12.0 * delta),
\t                          lerpf(cur_y, tgt.y, 12.0 * delta))

\t# Spawn loop
\tvar st: float = float(game.spawn_timer) - delta
\tif st <= 0.0:
\t\tst = __SPAWN_INTERVAL__
\t\t_spawn_target()
\tgame.spawn_timer = st

\t# Decay lifetimes; drop expired
\tvar kept: Array = []
\tfor t in game.targets:
\t\tt["life"] = float(t["life"]) - delta
\t\tif float(t["life"]) > 0.0:
\t\t\tkept.append(t)
\tgame.targets = kept

\t# Dwell-to-hit (face cursor over target for DWELL_THRESHOLD seconds)
\tvar r_sq: float = TAP_RADIUS * TAP_RADIUS
\tvar cursor_pos: Vector2 = Vector2(float(game.cursor_pos.x), float(game.cursor_pos.y))
\tvar hovered_id: int = -1
\tvar hovered_target: Dictionary = {}
\tfor t in game.targets:
\t\tvar dx: float = float(t["x"]) - cursor_pos.x
\t\tvar dy: float = float(t["y"]) - cursor_pos.y
\t\tif dx * dx + dy * dy < r_sq:
\t\t\thovered_id = int(t["id"])
\t\t\thovered_target = t
\t\t\tbreak
\tif hovered_id >= 0:
\t\tif int(game.dwell_anchor_id) == hovered_id:
\t\t\tgame.dwell_time = float(game.dwell_time) + delta
\t\t\tif float(game.dwell_time) >= DWELL_THRESHOLD:
\t\t\t\t_resolve_hit(hovered_target)
\t\t\t\tgame.dwell_anchor_id = -1
\t\t\t\tgame.dwell_time = 0.0
\t\telse:
\t\t\tgame.dwell_anchor_id = hovered_id
\t\t\tgame.dwell_time = 0.0
\telse:
\t\tgame.dwell_anchor_id = -1
\t\tgame.dwell_time = 0.0

\t# Win condition
\tif score >= __WIN_SCORE__:
\t\t_audio_play("__SFX_GAMEOVER__")
\t\tstate = GameState.GAME_OVER


func _draw_gameplay() -> void:
\tfor t in game.targets:
\t\tvar pos: Vector2 = Vector2(float(t["x"]), float(t["y"]))
\t\tvar life: float = float(t["life"])
\t\tvar fade: float = clampf(life / TARGET_FADE_TAIL, 0.0, 1.0)
\t\tvar pulse: float = 1.0 + 0.08 * sin(anim_timer * 8.0 + float(t["x"]) * 0.01)
\t\tvar size: float = 80.0 * pulse * fade
\t\tvar kind: String = String(t["kind"])
\t\tif kind == "target":
\t\t\t_draw_sprite_or_circle(game.target_tex, pos, size, 32.0 * fade, __TARGET_COLOR__)
\t\telse:
\t\t\t_draw_sprite_or_circle(game.decoy_tex, pos, size, 32.0 * fade, __DECOY_COLOR__)

\t# Face cursor (only when face/body actually tracked — avoid showing on touch-only sessions)
\tif bridge != null and (bridge.face_detected or bridge.body_detected):
\t\tvar cx: float = float(game.cursor_pos.x)
\t\tvar cy: float = float(game.cursor_pos.y)
\t\tdraw_circle(Vector2(cx, cy), 16.0, Color(1.0, 1.0, 1.0, 0.35))
\t\tdraw_circle(Vector2(cx, cy), 8.0, Color(1.0, 0.85, 0.10, 0.9))
\t\t# Dwell progress arc
\t\tif int(game.dwell_anchor_id) >= 0:
\t\t\tvar prog: float = clampf(float(game.dwell_time) / DWELL_THRESHOLD, 0.0, 1.0)
\t\t\tvar end_angle: float = -PI * 0.5 + prog * TAU
\t\t\tdraw_arc(Vector2(cx, cy), 22.0, -PI * 0.5, end_angle, 24, Color(0.20, 0.95, 0.35, 0.95), 3.0)


# ─── Tap handler — dispatched from skeleton _handle_gameplay_tap ─────────────

func _on_tap(pos: Vector2) -> void:
\tvar r_sq: float = TAP_RADIUS * TAP_RADIUS
\tfor t in game.targets:
\t\tif float(t["life"]) <= 0.0:
\t\t\tcontinue
\t\tvar dx: float = float(t["x"]) - pos.x
\t\tvar dy: float = float(t["y"]) - pos.y
\t\tif dx * dx + dy * dy < r_sq:
\t\t\t_resolve_hit(t)
\t\t\treturn


# ─── Helpers (whack_v1) ──────────────────────────────────────────────────────

func _resolve_hit(t: Dictionary) -> void:
\tt["life"] = 0.0
\tvar kind: String = String(t["kind"])
\tif kind == "target":
\t\tscore += __SCORE_VALUE__
\t\t_audio_play("__SFX_PICKUP__")
\telse:
\t\tlives -= __LIVES_COST__
\t\t_audio_play("__SFX_HIT__")


func _spawn_target() -> void:
\tvar sx: float = randf_range(100.0, screen_size.x - 100.0)
\tvar sy: float = randf_range(140.0, screen_size.y - 100.0)
\tvar is_decoy: bool = randf() < __DECOY_PROBABILITY__
\tvar kind: String = "decoy" if is_decoy else "target"
\tvar new_id: int = int(game.next_target_id)
\tgame.next_target_id = new_id + 1
\tgame.targets.append({"x": sx, "y": sy, "life": TARGET_LIFETIME, "kind": kind, "id": new_id})


func _draw_sprite_or_circle(tex: Texture2D, pos: Vector2, sprite_size: float, circle_rad: float, fallback: Color) -> void:
\tif tex != null:
\t\tvar half: float = sprite_size * 0.5
\t\tdraw_texture_rect(tex, Rect2(pos.x - half, pos.y - half, sprite_size, sprite_size), false)
\telse:
\t\tdraw_circle(pos, circle_rad, fallback)
"""


