"""whack_v1 — 拍打 archetype 实现。

玩法：目标（target）和诱饵（decoy）随机出现在屏幕各位置，每个限时存在
1.5 秒后消失。Tap 中 target=+score，tap 中 decoy=-life。win_score 决胜，
lives=0 失败。

跟 catch/dodger 不一样：纯触屏交互，不用左右位移控制器。复用 Entities
slot：`drop`=target（拍中得分）、`obstacle`=decoy（拍中扣命）。player slot
保留但不渲染（拍打游戏没有玩家 avatar）。

GDScript 使用 skeleton 新增的 `_on_tap(pos)` dispatch 钩子，避免与 plumbing
的 `_handle_gameplay_tap` 撞名 Parse Error。
"""

